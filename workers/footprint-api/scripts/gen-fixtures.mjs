// bakes fixtures/pages/*.html and fixtures/robots/*.txt into a ts module, so the worker can serve them in
// fixture mode without a filesystem. photos stay as files (served via the assets binding).
// run: pnpm --filter @unlisted/footprint-api gen:fixtures
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (dir, ext) =>
  Object.fromEntries(
    readdirSync(join(root, "fixtures", dir))
      .filter((f) => f.endsWith(ext))
      .sort()
      .map((f) => [f.slice(0, -ext.length), readFileSync(join(root, "fixtures", dir, f), "utf8")]),
  );

const photos = readdirSync(join(root, "fixtures", "photos"))
  .filter((f) => f.endsWith(".jpg"))
  .sort()
  .map((f) => f.slice(0, -4));

const out = `// generated by scripts/gen-fixtures.mjs, don't hand-edit. synthetic data only.
export const PAGES: Record<string, string> = ${JSON.stringify(read("pages", ".html"), null, 2)};

export const ROBOTS: Record<string, string> = ${JSON.stringify(read("robots", ".txt"), null, 2)};

export const PHOTOS: string[] = ${JSON.stringify(photos)};
`;
writeFileSync(join(root, "src", "fixtures.generated.ts"), out);
console.log("wrote src/fixtures.generated.ts");
